"""
ボラ分析のたたき台ブック(VolLab.xlsx)。インプライド(スワップションATMノーマルvol)と
リアライズド(Fwdスワップレートの日次変化)を比べて、割安・割高を考えるための実験用。

    python -m tools.vol_lab            # DBのデータをVolLab.xlsxに書き込む(無ければ雛形からコピー)
    python -m tools.vol_lab --build    # ブックの構成(シート・数式・グラフ)を作り直す(開発用)

■ 役割の分担
  - Python(data.py): QuantLibでしか出せない値だけを作る。日次カーブDBから、満期x原資産ごとの
    Fwdスワップレート・日次変化・二乗の累積・満期までの日数・オプション追跡型の二乗和。
    書き込みはブックのデータシートの3行目以降だけ(fill.py。Excelを使わずxlsxを直接書き換える
    ので、グラフ・数式・設定はそのまま残る)。
  - Excel: それ以外の全部(RV・EWMA・zスコア・ボラコーン・フォワードボラ・GARCH等)を数式で。
    設定シートの値(年営業日数・窓・λ等)を変えると、その場で全体が変わる。

■ 本番の設計方針との関係
  たたき台なのでUDF(xlwings)を使わず、データを値として書き込む。CLAUDE.mdの「UDFセルを静的値で
  上書きしない」はPricingSheetの事故への対策で、UDFを持たないこのブックには当たらない。
  使い方が固まったら、本番(SwapAnalysis)ではUDFとして作り直す。

■ Fwdの日付の決め方
  評価日tの「満期e x 原資産n」の原資産 = tのスポット日+e を起算日とするn年のOIS(標準の規約)。
  オプションの満期日 = 起算日(休日調整後)の2営業日前。
  - 満期一定型(B): 毎日起算日を付け直す。1日の変化は「前日と当日で同じ起算日・満期日」の差
    (ロールダウンを混ぜない)。
  - オプション追跡型(A): 取引日に決めた起算日・満期日を満期まで固定して追う(実際にそのオプションを
    持った人が経験したボラ)。満期1Y以下だけ。
"""
